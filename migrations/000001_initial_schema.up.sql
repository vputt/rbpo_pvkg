CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    failed_login_count INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_login_unique UNIQUE (login),
    CONSTRAINT users_role_check CHECK (role IN ('user', 'staff')),
    CONSTRAINT users_failed_login_count_check CHECK (failed_login_count >= 0)
);

CREATE TABLE sessions (
    token_hash BYTEA PRIMARY KEY,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT sessions_token_hash_length_check CHECK (octet_length(token_hash) = 32),
    CONSTRAINT sessions_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    public_description TEXT NOT NULL,
    found_place TEXT NOT NULL,
    found_at TIMESTAMPTZ NOT NULL,
    storage_location TEXT NOT NULL,
    private_marks TEXT NOT NULL,
    status TEXT NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT items_status_check CHECK (status IN ('available', 'reserved', 'issued')),
    CONSTRAINT items_created_by_fkey
        FOREIGN KEY (created_by) REFERENCES users (id)
);

CREATE TABLE claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    ownership_marks TEXT NOT NULL,
    loss_circumstances TEXT NOT NULL,
    status TEXT NOT NULL,
    decided_by BIGINT,
    decided_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT claims_status_check
        CHECK (status IN ('pending', 'approved', 'completed', 'rejected')),
    CONSTRAINT claims_item_id_fkey
        FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT claims_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT claims_decided_by_fkey
        FOREIGN KEY (decided_by) REFERENCES users (id)
);

CREATE UNIQUE INDEX claims_one_approved_per_item
    ON claims (item_id)
    WHERE status = 'approved';

CREATE TABLE issuances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL,
    claim_id BIGINT NOT NULL,
    issued_by BIGINT NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT issuances_item_id_unique UNIQUE (item_id),
    CONSTRAINT issuances_claim_id_unique UNIQUE (claim_id),
    CONSTRAINT issuances_item_id_fkey
        FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT issuances_claim_id_fkey
        FOREIGN KEY (claim_id) REFERENCES claims (id),
    CONSTRAINT issuances_issued_by_fkey
        FOREIGN KEY (issued_by) REFERENCES users (id)
);
